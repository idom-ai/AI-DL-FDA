"""BLOCK 5: visualization. Plots, no calculations: scikit-fda draws the FDataGrid objects."""
import matplotlib.pyplot as plt
import numpy as np
from flow_matching_fda.flow_matching import functions_at


def plot_originals(data, n=15):
    """Plots the training functions."""
    fig, ax = plt.subplots(figsize=(6, 4))
    data[:n].plot(axes=ax)
    ax.set_ylim(-3, 3)
    ax.set_title("Training functions")
    fig.tight_layout()
    fig.savefig("originals.png", dpi=150)


def plot_evolution(trajectory, n=30, panels=6, title="Generation: from noise to the function", path="evolution.png"):
    """Noise evolution turning into functions.

    Each panel is an instant tau of the ODE; each color is the same sample along time.
    """
    taus = trajectory.grid_points[0]
    steps = len(taus) - 1
    fig, axes = plt.subplots(1, panels, figsize=(3 * panels, 3), sharey=True)
    for ax, k in zip(axes, np.linspace(0, steps, panels, dtype=int)):
        functions_at(trajectory, k)[:n].plot(axes=ax, linewidth=1)
        ax.set_title(f"τ = {taus[k]:.1f}")
        ax.set_ylim(-3, 3)
    fig.suptitle(title)
    fig.tight_layout()
    fig.savefig(path, dpi=150)


def plot_losses(losses, path="losses.png"):
    """Training loss (CFM) of each epoch, for the experiments trained in one single phase."""
    fig, ax = plt.subplots(figsize=(6, 4))
    ax.plot(range(1, len(losses) + 1), losses)
    ax.set_yscale("log")
    ax.set_xlabel("epoch")
    ax.set_ylabel("CFM loss")
    ax.set_title("Training loss")
    fig.tight_layout()
    fig.savefig(path, dpi=150)


def plot_fine_tuning_losses(losses_phase_1, losses_phase_2, path="losses.png"):
    """Training loss (CFM) of each epoch for the fine-tuning, which has two phases one after the other.

    Phase 1: backbone frozen. Phase 2: everything unfrozen. The dashed line marks the change of phase.
    """
    n_1, n_2 = len(losses_phase_1), len(losses_phase_2)
    fig, ax = plt.subplots(figsize=(8, 4))
    ax.plot(range(1, n_1 + 1), losses_phase_1, label="phase 1: backbone frozen")
    ax.plot(range(n_1 + 1, n_1 + n_2 + 1), losses_phase_2, label="phase 2: everything unfrozen")
    ax.axvline(n_1 + 0.5, color="gray", linestyle="--", linewidth=1)
    ax.set_yscale("log")
    ax.set_xlabel("epoch")
    ax.set_ylabel("CFM loss")
    ax.set_title("Fine-tuning loss")
    ax.legend()
    fig.tight_layout()
    fig.savefig(path, dpi=150)


def plot_final_comparison(generated, n=30, path="final_comparison.png"):
    """Generated functions at the end of the ODE (tau = 1), one panel per model.

    generated: dict {model name: FDataGrid with the functions generated by that model}.
    Generate them all from the same initial noise, so that the only difference between panels is the model.
    """
    fig, axes = plt.subplots(1, len(generated), figsize=(4 * len(generated), 3.5), sharey=True, squeeze=False)
    for ax, (name, functions) in zip(axes[0], generated.items()):
        functions[:n].plot(axes=ax, linewidth=1)
        ax.set_title(name)
        ax.set_ylim(-1.5, 1.5)
    fig.suptitle("Generated functions (τ = 1) of each model, from the same noise")
    fig.tight_layout()
    fig.savefig(path, dpi=150)
